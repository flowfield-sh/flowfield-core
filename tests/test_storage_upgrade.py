"""Upgrade published schemas without changing authored or delivered evidence."""

import hashlib
import json
import sqlite3
from pathlib import Path

import pytest

from flowfield import storage
from flowfield.application import TaskCreate, Workspace
from flowfield.browser import BrowserReads
from flowfield.errors import ApplicationError
from flowfield.schema import SCHEMA_VERSION


def published(tmp_path, version=86):
    fixtures = Path(__file__).parent / "fixtures"
    directory = tmp_path / "state"
    directory.mkdir()
    sql = (
        (fixtures / "published-schema-86.sql")
        .read_text()
        .replace("/fixture/schema-86", str(tmp_path))
    )
    with sqlite3.connect(directory / storage.DATABASE) as db:
        db.executescript(sql)
        if version == 87:
            db.execute(storage.TASK_DELETIONS)
            db.execute(f"PRAGMA user_version={version}")
    info = json.loads((fixtures / "published-schema-86.json").read_text())
    output = directory / "workspaces" / "harbor" / "outputs" / info["output_id"]
    output.parent.mkdir(parents=True)
    output.write_text(info["output_text"])
    return directory, output, info


def rows(database):
    with sqlite3.connect(database) as db:
        names = [
            row[0]
            for row in db.execute(
                "SELECT name FROM sqlite_master WHERE type='table' "
                "AND name NOT LIKE 'search_docs%' AND name NOT LIKE 'usage_%' "
                "AND name NOT IN ('task_deletions','worker_check_grants')"
            )
        ]
        values = {
            name: db.execute(
                (
                    f'SELECT number,id,workspace_id,run_id,data FROM "{name}"'
                    if name == "output_files"
                    else f'SELECT * FROM "{name}"'
                )
                + (" WHERE name NOT LIKE 'usage_%'" if name == "sqlite_sequence" else "")
            ).fetchall()
            for name in names
        }
        # The runtime upgrade adds a frozen recipe, not new authored/approval evidence.
        # Compare every existing field; recipe provenance is tested independently below.
        if "result_versions" in values:
            normalized = []
            columns = [row[1] for row in db.execute("PRAGMA table_info(result_versions)")]
            index = columns.index("data")
            for row in values["result_versions"]:
                cells = list(row)
                value = json.loads(cells[index])
                value.pop("recipe", None)
                cells[index] = json.dumps(value, sort_keys=True)
                normalized.append(tuple(cells))
            values["result_versions"] = normalized
        return values


@pytest.mark.parametrize("version", [86, 87])
def test_published_upgrade_preserves_every_row_and_file_with_verified_recovery(tmp_path, version):
    directory, output, info = published(tmp_path, version)
    before = rows(directory / storage.DATABASE)
    store = Workspace(directory)
    assert rows(store.database) == before
    assert storage.status(directory)["schema_version"] == SCHEMA_VERSION
    assert hashlib.sha256(output.read_bytes()).hexdigest() == info["sha256"]
    backups = list((directory / "backups").glob(f"schema-{version}-*.sqlite3"))
    assert len(backups) == 1 and rows(backups[0]) == before
    with sqlite3.connect(backups[0]) as db:
        assert storage.version(db) == version
        storage.integrity(db)
    board = BrowserReads(store).workspace_board("harbor")
    assert {task.status for task in board.tasks} == {"done", "backlog"}
    assert store.task("harbor", "T-1").status == "done"
    Workspace(directory)
    assert list((directory / "backups").glob("*.sqlite3")) == backups
    new = store.create_task("harbor", TaskCreate(title="First edit after upgrade"))
    assert new.key == "T-3"


def test_upgrade_failure_rolls_back_and_retry_preserves_recovery(tmp_path, monkeypatch):
    directory, output, _ = published(tmp_path)
    before = rows(directory / storage.DATABASE)
    migration = storage.TASK_DELETIONS
    monkeypatch.setattr(storage, "TASK_DELETIONS", "CREATE TABLE tasks (id TEXT)")
    with pytest.raises(sqlite3.OperationalError):
        Workspace(directory)
    assert storage.status(directory)["schema_version"] == 86
    assert rows(directory / storage.DATABASE) == before
    assert output.exists()
    monkeypatch.setattr(storage, "TASK_DELETIONS", migration)
    assert Workspace(directory).task("harbor", "T-1").status == "done"


def test_release_010_removes_draft_gate_without_starting_previously_excluded_work(tmp_path):
    directory = tmp_path / "state"
    directory.mkdir()
    database = directory / storage.DATABASE
    # Generated by the actual v0.10.0 package source, not the new application model.
    with sqlite3.connect(database) as db:
        db.executescript((Path(__file__).parent / "fixtures/published-schema-92.sql").read_text())
        workspace = db.execute("SELECT id FROM workspaces").fetchone()[0]
        history = db.execute("SELECT * FROM task_revisions").fetchall()
        settings = db.execute("SELECT * FROM workspace_worker_settings").fetchall()
    store = Workspace(directory)
    assert storage.status(directory)["schema_version"] == SCHEMA_VERSION
    tasks = {task.id: task for task in store.tasks(workspace)}
    assert tasks["unscheduled"].status == "backlog"
    assert tasks["unprepared"].status == tasks["changed"].status == "backlog"
    assert tasks["ready"].status == "up_next"
    assert tasks["unprepared"].readiness == tasks["changed"].readiness == "ready"
    assert tasks["unscheduled"].readiness == "blocked"
    assert all("publication_status" not in task.model_dump() for task in tasks.values())
    with store.connection() as db:
        assert [
            tuple(row) for row in db.execute("SELECT * FROM workspace_worker_settings")
        ] == settings
        for row in history:
            assert (
                tuple(
                    db.execute(
                        "SELECT * FROM task_revisions WHERE workspace_id=? "
                        "AND task_id=? AND revision=?",
                        row[:3],
                    ).fetchone()
                )
                == row
            )
        assert db.execute("SELECT count(*) FROM runs").fetchone()[0] == 0
    backups = list((directory / "backups").glob("schema-92-*.sqlite3"))
    assert len(backups) == 1
    Workspace(directory)
    assert list((directory / "backups").glob("schema-92-*.sqlite3")) == backups


@pytest.mark.parametrize("harness", ["claude-code", "codex", "pi"])
def test_0101_upgrade_starts_only_claude_fresh_and_preserves_saved_work(
    tmp_path, monkeypatch, harness
):
    directory = tmp_path / "state"
    directory.mkdir()
    database = directory / storage.DATABASE
    with sqlite3.connect(database) as db:
        db.executescript((Path(__file__).parent / "fixtures/published-schema-93.sql").read_text())
        workspace = db.execute("SELECT id FROM workspaces").fetchone()[0]
        # Native-generation JSON from the published model, without new runtime flags.
        generation = json.dumps(
            dict(
                id="saved-generation",
                workspace_id=workspace,
                session_id="saved-native",
                created_at="2026-10-30T12:00:00Z",
                harness=harness,
                cwd="/retained/repository",
                status="retained",
                dispatched=True,
            )
        )
        db.execute(
            "INSERT INTO coordinator_session_generations VALUES (?,?,?)",
            ("saved-generation", workspace, generation),
        )
        db.execute(
            "INSERT INTO coordinator_sessions VALUES (?, ?, 0)", (workspace, "saved-generation")
        )
    before = rows(database)
    original = storage.integrity

    def fail_after_boundary(db):
        original(db)
        if storage.version(db) == SCHEMA_VERSION:
            raise RuntimeError("interrupted after session boundary")

    monkeypatch.setattr(storage, "integrity", fail_after_boundary)
    with pytest.raises(RuntimeError, match="interrupted"):
        Workspace(directory)
    assert rows(database) == before
    assert storage.status(directory)["schema_version"] == 93
    monkeypatch.setattr(storage, "integrity", original)
    store = Workspace(directory)
    after = rows(database)
    expected = dict(before)
    expected["coordinator_sessions"] = [
        (workspace, "saved-generation", int(harness == "claude-code"))
    ]
    assert {name: after[name] for name in before} == expected
    backups = list((directory / "backups").glob("schema-93-*.sqlite3"))
    assert len(backups) == 2 and all(rows(backup) == before for backup in backups)
    # A normal later startup must never repeat the one-time session break.
    with store.connection(write=True) as db:
        db.execute("UPDATE coordinator_sessions SET fresh=0")
    Workspace(directory)
    with store.connection() as db:
        assert db.execute("SELECT fresh FROM coordinator_sessions").fetchone()[0] == 0
    assert list((directory / "backups").glob("schema-93-*.sqlite3")) == backups
    assert (
        store.create_task(workspace, TaskCreate(title="Work after upgrade")).title
        == "Work after upgrade"
    )


def test_upgrade_requires_exclusive_execution_and_old_open_store_cannot_write(tmp_path):
    directory, _, _ = published(tmp_path)
    before = (directory / storage.DATABASE).read_bytes()
    with storage.acquire_lock(directory, ".execution.lock"):
        with pytest.raises(ApplicationError, match="Preserve"):
            Workspace(directory)
    assert (directory / storage.DATABASE).read_bytes() == before
    assert not (directory / "backups").exists()
    store = Workspace(directory)
    # A process that opened the published schema must not write the upgraded database.
    store.schema_version = 86
    with pytest.raises(ApplicationError, match="opened schema 86"):
        store.create_task("harbor", TaskCreate(title="Stale process"))


def test_draft_retirement_rolls_back_current_and_historical_records(tmp_path, monkeypatch):
    directory = tmp_path / "state"
    directory.mkdir()
    database = directory / storage.DATABASE
    with sqlite3.connect(database) as db:
        db.executescript((Path(__file__).parent / "fixtures/published-schema-92.sql").read_text())
    before = rows(database)
    original = storage.retire_task_drafts

    def interrupted(db):
        original(db)
        raise RuntimeError("Interrupted after task migration")

    with monkeypatch.context() as patch:
        patch.setattr(storage, "retire_task_drafts", interrupted)
        with pytest.raises(RuntimeError, match="Interrupted"):
            Workspace(directory)
    assert storage.status(directory)["schema_version"] == 92
    assert rows(database) == before
    Workspace(directory)
    assert storage.status(directory)["schema_version"] == SCHEMA_VERSION


def test_published_012_runtime_upgrade_preserves_records_without_auto_execution(tmp_path):
    directory = tmp_path / "state"
    directory.mkdir()
    database = directory / storage.DATABASE
    with sqlite3.connect(database) as db:
        db.executescript((Path(__file__).parent / "fixtures/published-schema-96.sql").read_text())
    before = rows(database)
    store = Workspace(directory)
    assert rows(database) == before
    assert storage.status(directory)["schema_version"] == SCHEMA_VERSION
    assert len(list((directory / "backups").glob("schema-96-*.sqlite3"))) == 1
    from flowfield.inspection import Inspections
    from flowfield.result_runtime import ResultRuntimes

    for project in store.projects():
        assert not Inspections(store).settings(project.id).auto_prepare
    runtimes = ResultRuntimes(store)
    runtimes.recover()
    assert not runtimes.jobs
    Workspace(directory)
    assert rows(database) == before
